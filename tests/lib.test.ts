describe("provider strategy", () => {
  const charging = { charging: true, source: "override" as const };
  const battery = { charging: false, source: "override" as const };

  test("uses the active provider first by default, then local as fallback", () => {
    const settings = mergeSettings({ activeProvider: "opencode-go", providerStrategy: { preferLocal: false, fallbackToLocalWhenOffline: true, localProvider: "ollama" } });
    const chain = resolveProviderChain(settings, battery, true);
    expect(chain.map((c) => c.kind)).toEqual(["opencode-go", "ollama"]);
  });

  test("prefers local while charging, remote while on battery", () => {
    const settings = mergeSettings({ activeProvider: "opencode-go", providerStrategy: { preferLocal: true, localOnlyWhenCharging: true, localProvider: "vllm" } });
    expect(resolveProviderChain(settings, charging, true).map((c) => c.kind)).toEqual(["vllm", "opencode-go"]);
    expect(resolveProviderChain(settings, battery, true).map((c) => c.kind)).toEqual(["opencode-go", "vllm"]);
  });

  test("prefers local regardless of power when not limited to charging", () => {
    const settings = mergeSettings({ activeProvider: "opencode-go", providerStrategy: { preferLocal: true, localOnlyWhenCharging: false, localProvider: "ollama" } });
    expect(resolveProviderChain(settings, battery, true).map((c) => c.kind)).toEqual(["ollama", "opencode-go"]);
  });

  test("uses only the local provider when offline", () => {
    const settings = mergeSettings({ activeProvider: "opencode-go", providerStrategy: { preferLocal: false, fallbackToLocalWhenOffline: true, localProvider: "ollama" } });
    const chain = resolveProviderChain(settings, battery, false);
    expect(chain.map((c) => c.kind)).toEqual(["ollama"]);
    expect(chain[0].reason).toContain("offline");
  });

  test("deduplicates when the active provider is also the local provider", () => {
    const settings = mergeSettings({ activeProvider: "ollama", providerStrategy: { preferLocal: true, localOnlyWhenCharging: false, localProvider: "ollama" } });
    expect(resolveProviderChain(settings, battery, true).map((c) => c.kind)).toEqual(["ollama"]);
  });
});

describe("shortcuts", () => {
  test("formats a modifier + key combination", () => {
    expect(formatShortcut({ key: "a", altKey: true, shiftKey: true })).toBe("Alt+Shift+A");
    expect(formatShortcut({ key: "e", altKey: true, shiftKey: true })).toBe("Alt+Shift+E");
    expect(formatShortcut({ key: "1", ctrlKey: true, metaKey: true })).toBe("Ctrl+Command+1");
  });

  test("rejects modifier-only presses", () => {
    expect(formatShortcut({ key: "Shift", shiftKey: true })).toBeNull();
    expect(formatShortcut({ key: "Alt", altKey: true })).toBeNull();
  });

  test("allows function keys without a modifier, rejects bare letters", () => {
    expect(formatShortcut({ key: "F8" })).toBe("F8");
    expect(formatShortcut({ key: "a" })).toBeNull();
  });

  test("normalizes Space and arrows", () => {
    expect(formatShortcut({ key: " ", altKey: true })).toBe("Alt+Space");
    expect(formatShortcut({ key: "ArrowUp", ctrlKey: true })).toBe("Ctrl+Up");
  });
});

