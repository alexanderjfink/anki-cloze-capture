describe("image cards", () => {
  const imageCard = (over: Partial<Parameters<typeof buildImageFields>[0]> = {}) => ({
    kind: "image" as const,
    text: "Mitochondrion",
    backExtra: "",
    deck: "Biology",
    imageSide: "front" as const,
    bothDirections: true,
    image: { sourceUrl: "https://e.com/a.png", mime: "image/png" },
    ...over,
  });

  test("image on front puts the image on Front and text + source on Back", () => {
    const { modelName, fields } = buildImageFields(imageCard(), DEFAULT_SETTINGS, "https://page.com/x", "acc-img-abc.png");
    expect(modelName).toBe("Basic (and reversed card)");
    expect(fields.Front).toBe('<img src="acc-img-abc.png">');
    expect(fields.Back).toContain("Mitochondrion");
    expect(fields.Back).toContain('Source: <a href="https://page.com/x">https://page.com/x</a>');
  });

  test("image on back puts text + source on Front", () => {
    const { fields } = buildImageFields(imageCard({ imageSide: "back" }), DEFAULT_SETTINGS, "https://page.com/x", "img.png");
    expect(fields.Back).toBe('<img src="img.png">');
    expect(fields.Front).toContain("Mitochondrion");
    expect(fields.Front).toContain("Source:");
  });

  test("one-way uses the one-way model", () => {
    const { modelName } = buildImageFields(imageCard({ bothDirections: false }), DEFAULT_SETTINGS, "u", "i.png");
    expect(modelName).toBe("Basic");
  });

  test("escapes HTML in the text and URL", () => {
    const { fields } = buildImageFields(
      imageCard({ text: "<b>x</b>" }),
      DEFAULT_SETTINGS,
      "https://page.com/?a=1&b=2",
      "i.png",
    );
    expect(fields.Back).toContain("&lt;b&gt;x&lt;/b&gt;");
    expect(fields.Back).toContain("a=1&amp;b=2");
  });
});

describe("media helpers", () => {
  test("maps mime types to file extensions", () => {
    expect(extensionForMime("image/jpeg")).toBe("jpg");
    expect(extensionForMime("image/svg+xml")).toBe("svg");
    expect(extensionForMime("image/webp")).toBe("webp");
    expect(extensionForMime("image/unknown")).toBe("png");
  });

  test("guesses mime from a URL", () => {
    expect(guessMimeFromUrl("https://a/b.PNG?x=1")).toBe("image/png");
    expect(guessMimeFromUrl("https://a/b.webp")).toBe("image/webp");
    expect(guessMimeFromUrl("https://a/noext")).toBe("image/png");
  });

  test("parses base64 data URLs", () => {
    expect(dataUrlToRef("data:image/png;base64,AAAA")).toEqual({ mime: "image/png", dataBase64: "AAAA" });
  });

  test("builds deterministic content-hash filenames", async () => {
    const a = await mediaFilename("AAAA", "image/png");
    const b = await mediaFilename("AAAA", "image/png");
    expect(a).toBe(b);
    expect(a).toMatch(/^acc-img-[0-9a-f]{20}\.png$/);
  });
});

describe("page markers", () => {
  test("normalizes URLs by dropping hash and tracking params", () => {
    const a = normalizeUrl("https://en.wikipedia.org/wiki/Mitochondrion?utm_source=x&gclid=1#Section", true);
    expect(a).toBe("https://en.wikipedia.org/wiki/Mitochondrion");
    const b = normalizeUrl("https://example.com/a?keep=1&utm_medium=y", true);
    expect(b).toBe("https://example.com/a?keep=1");
    const c = normalizeUrl("https://example.com/a?utm_medium=y#x", false);
    expect(c).toBe("https://example.com/a?utm_medium=y");
  });

  test("finds the occurrence best matching prefix and suffix", () => {
    const full = "The cat sat. The cat ran. The cat sat again.";
    const match = findBestMatch(full, "The cat", "sat. ", " ran");
    expect(match).not.toBeNull();
    expect(full.slice(match!.index, match!.index + match!.length)).toBe("The cat");
    // Should pick the "The cat ran" occurrence (prefix "sat. ") over the first.
    expect(full.slice(match!.index, match!.index + 11)).toBe("The cat ran");
  });

  test("returns null when the quote is absent", () => {
    expect(findBestMatch("hello world", "goodbye", "", "")).toBeNull();
  });

  test("does not match in the middle of a word", () => {
    expect(findBestMatch("highlight reactions are here", "light reactions", "", "")).toBeNull();
    expect(findBestMatch("the light reactions are here", "light reactions", "", "")).not.toBeNull();
    // Picks the boundary-aligned occurrence, skipping the mid-word one.
    const match = findBestMatch("highlight nothing. the light reactions.", "light reactions", "", "");
    expect(match).not.toBeNull();
    expect(match!.index).toBe("highlight nothing. the ".length);
  });

  test("fuzzyQuote ignores mid-word occurrences", () => {
    expect(fuzzyQuote("highlight reactions happen", "light reactions happen")).toBeNull();
  });

  test("fuzzyQuote finds a verbatim window when the full sentence is rephrased", () => {
    const page =
      "Photosynthesis occurs in two main stages: the light-dependent reactions and the Calvin cycle, which happens in the stroma.";
    const sentence = "Plants perform the light-dependent reactions and the Calvin cycle during the day.";
    const q = fuzzyQuote(page, sentence);
    expect(q).not.toBeNull();
    expect(page.includes(q as string)).toBe(true);
    expect((q as string).split(" ").length).toBeGreaterThanOrEqual(5);
  });

  test("fuzzyQuote returns the sentence when present verbatim", () => {
    expect(fuzzyQuote("The mitochondrion generates ATP.", "generates ATP")).toBe("generates ATP");
  });

  test("splits the mandatory Source line off editable text", () => {
    const value = "Some context<br><br>Source: <a href=\"https://e.com/x\">https://e.com/x</a>";
    const { body, source } = splitSource(value);
    expect(body).toBe("Some context");
    expect(source).toContain("Source:");
    expect(source).toContain("https://e.com/x");
  });

  test("leaves plain values untouched", () => {
    const { body, source } = splitSource("The {{c1::mitochondria}} is the powerhouse.");
    expect(body).toContain("{{c1::mitochondria}}");
    expect(source).toBe("");
  });
});

describe("hypothesis", () => {
  test("maps a TextQuoteSelector to a page anchor", () => {
    const anchor = selectorToAnchor({
      id: "abc",
      target: [{ selector: [{ type: "TextQuoteSelector", exact: "mitochondria", prefix: "the ", suffix: " is" }] }],
    });
    expect(anchor).toEqual({ kind: "text", quote: "mitochondria", prefix: "the ", suffix: " is" });
  });

  test("returns null for page notes without a selector", () => {
    expect(selectorToAnchor({ id: "x", target: [{ source: "https://e.com" }] })).toBeNull();
  });

  test("parses a search response, keeping highlights and note text", () => {
    const response = {
      rows: [
        {
          id: "h1",
          uri: "https://e.com/a",
          text: "my note",
          target: [{ selector: [{ type: "TextQuoteSelector", exact: "ATP", prefix: "supply of ", suffix: " which" }] }],
        },
        { id: "p1", uri: "https://e.com/a", text: "a page note", target: [{ source: "https://e.com/a" }] },
      ],
    };
    const parsed = parseAnnotations(response);
    expect(parsed).toHaveLength(1);
    expect(parsed[0]).toMatchObject({ id: "h1", exact: "ATP", prefix: "supply of ", suffix: " which", noteText: "my note" });
  });

  test("content keys are stable and distinct", () => {
    const a = { kind: "text" as const, quote: "x", prefix: "a", suffix: "b" };
    const b = { kind: "text" as const, quote: "x", prefix: "a", suffix: "c" };
    expect(contentKey("u", a)).toBe(contentKey("u", a));
    expect(contentKey("u", a)).not.toBe(contentKey("u", b));
  });

  test("hypothesis integration is off by default", () => {
    expect(mergeSettings({}).hypothesis.mode).toBe("off");
  });
});

