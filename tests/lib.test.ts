describe("quality", () => {
  test("extracts cloze answers and hints", () => {
    const parts = extractClozes("The {{c1::Olmec::civilization}} carved {{c2::stone heads}}.");
    expect(parts).toHaveLength(2);
    expect(parts[0]).toMatchObject({ num: 1, answer: "Olmec", hint: "civilization" });
    expect(parts[1]).toMatchObject({ num: 2, answer: "stone heads" });
  });

  test("flags clozes longer than the word limit", () => {
    const issues = validateCard(
      { text: "They carved {{c1::immense stone heads}} from rock.", backExtra: "" },
      2,
    );
    expect(issues.some((i) => i.includes("max 2"))).toBe(true);
  });

  test("flags answer giveaways", () => {
    const issues = validateCard({ text: "The {{c1::invisible hand}} is the invisible hand concept.", backExtra: "" }, 2);
    expect(issues.some((i) => i.includes("giveaway"))).toBe(true);
  });

  test("accepts a good card", () => {
    const issues = validateCard(
      { text: "The Olmec carved {{c1::stone heads::monuments}} from {{c2::basalt}}.", backExtra: "context" },
      2,
    );
    expect(issues).toEqual([]);
  });

  test("parses a fenced JSON response", () => {
    const raw = '```json\n{"cards":[{"text":"A {{c1::B}} C.","backExtra":""}]}\n```';
    const result = parseCardResponse(raw, 2);
    expect(result.error).toBeUndefined();
    expect(result.cards[0].text).toBe("A {{c1::B}} C.");
  });

  test("returns an error for non-JSON", () => {
    const result = parseCardResponse("no json here", 5);
    expect(result.error).toBeDefined();
    expect(result.cards).toHaveLength(0);
  });

  test("parses the source quote used for anchoring autogenerated cards", () => {
    const raw = '{"cards":[{"text":"A {{c1::B}} C.","backExtra":"","source":"The exact sentence from the page."}]}';
    const result = parseCardResponse(raw, 2);
    expect(result.cards[0].sourceQuote).toBe("The exact sentence from the page.");
  });
});

describe("embeddings", () => {
  test("cosine similarity of identical vectors is 1", () => {
    expect(cosineSimilarity([1, 2, 3], [1, 2, 3])).toBeCloseTo(1, 6);
  });
  test("cosine similarity of orthogonal vectors is 0", () => {
    expect(cosineSimilarity([1, 0], [0, 1])).toBeCloseTo(0, 6);
  });
  test("mismatched lengths return 0", () => {
    expect(cosineSimilarity([1, 2], [1])).toBe(0);
  });
});

